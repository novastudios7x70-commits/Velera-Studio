// Small formatting helpers shared across server and client components.

export function timeAgo(iso: string) {
  const diffMs = Date.now() - new Date(iso).getTime();
  const mins = Math.floor(diffMs / 60000);
  if (mins < 1) return "just now";
  if (mins < 60) return `${mins} min${mins === 1 ? "" : "s"} ago`;
  const hours = Math.floor(mins / 60);
  if (hours < 24) return `${hours} hour${hours === 1 ? "" : "s"} ago`;
  const days = Math.floor(hours / 24);
  return `${days} day${days === 1 ? "" : "s"} ago`;
}

/** Whether an ISO timestamp falls within the last `windowMs` milliseconds. */
export function isWithinLast(iso: string, windowMs: number) {
  return Date.now() - new Date(iso).getTime() < windowMs;
}
